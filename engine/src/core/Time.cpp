// ============================================================================
//  Time.cpp - the static reader in front of GameClock. See Time.h for what
//  the two deltas are and why there are two of them.
//
//  EVERY VALUE HERE COMES FROM THE CLOCK. Nothing is cached and nothing is
//  recomputed: this file holds exactly one piece of state of its own, the
//  phase flag, and everything else is forwarded. A cached copy would be a
//  second answer to the same question, and the two would eventually disagree.
// ============================================================================

#include <engine/core/Time.h>

#include <engine/Engine.h>
#include <engine/core/GameClock.h>

namespace eng {
namespace {

// Are we inside a fixed simulation step right now?
//
// A plain bool in an anonymous namespace, NOT a static member of Time, and
// that is a hard requirement rather than a preference: the engine is a DLL
// whose exports are generated by WINDOWS_EXPORT_ALL_SYMBOLS, which exports
// functions and NOT data. A static data member would link inside the engine
// and fail to resolve from a project's compiled scripts - which is the one
// place this class exists to be called from. See engine/CMakeLists.txt.
bool g_inFixedStep = false;

const GameClock& Clock() { return Engine::Get().Clock(); }

} // namespace

// ---------------------------------------------------------------------------
//  The deltas
// ---------------------------------------------------------------------------

float Time::DeltaTime() {
    // The branch that makes one name correct in both hooks. See Time.h.
    if (g_inFixedStep) {
        return Clock().FixedStepSeconds();
    }

    // Scaled, like Unity's Time.deltaTime - so that at a time scale of zero
    // this returns 0 and anything driven by it stops, while
    // UnscaledDeltaTime() keeps the menus moving.
    return Clock().RealDeltaSeconds() * Clock().TimeScale();
}

float Time::FixedDeltaTime()    { return Clock().FixedStepSeconds(); }
float Time::UnscaledDeltaTime() { return Clock().RealDeltaSeconds(); }

// ---------------------------------------------------------------------------
//  The timelines and the counters
// ---------------------------------------------------------------------------

double Time::ElapsedTime()         { return Clock().GameSeconds(); }
double Time::UnscaledElapsedTime() { return Clock().RealSeconds(); }

unsigned long long Time::FrameCount() { return Clock().FrameCount(); }
unsigned long long Time::TickCount()  { return Clock().TickCount(); }

// ---------------------------------------------------------------------------
//  The state of the clock
// ---------------------------------------------------------------------------

float Time::TimeScale() { return Clock().TimeScale(); }
bool  Time::IsPaused()  { return Clock().IsPaused(); }

// ---------------------------------------------------------------------------
//  The phase, set by Engine::Simulate
// ---------------------------------------------------------------------------

bool Time::InFixedStep() { return g_inFixedStep; }

void Time::BeginFixedStep() { g_inFixedStep = true; }
void Time::EndFixedStep()   { g_inFixedStep = false; }

} // namespace eng
